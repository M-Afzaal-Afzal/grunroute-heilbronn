// Copies the shared scoring code and data from the people app (repo root)
// into the Planner, so both apps read the same evidence. Runs before dev and
// build. The copies are gitignored: edit the root files, never the copies.
//
//   ../lib/<file>.ts (and every ./ import they pull in)  ->  lib/shared/
//   ../public/data/*                                     ->  public/data/
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const admin = resolve(here, "..");
const root = resolve(admin, "..");
const ENTRY = ["priority", "sources", "segments", "live", "tiles", "cityTrees", "atrai", "sun", "missions", "species"];
const HEADER = "// generated by admin/scripts/sync-shared.mjs, edit the root file in ../lib instead\n";

const libOut = join(admin, "lib/shared");
rmSync(libOut, { recursive: true, force: true });
mkdirSync(libOut, { recursive: true });
const done = new Set();
const queue = [...ENTRY];
while (queue.length) {
  const name = queue.shift();
  if (done.has(name)) continue;
  done.add(name);
  const src = join(root, "lib", `${name}.ts`);
  if (!existsSync(src)) throw new Error(`sync-shared: missing ${src}`);
  const code = readFileSync(src, "utf8");
  for (const m of code.matchAll(/from\s+"\.\/([\w-]+)"/g)) queue.push(m[1]);
  writeFileSync(join(libOut, `${name}.ts`), HEADER + code);
}

const dataSrc = join(root, "public/data");
const dataOut = join(admin, "public/data");
mkdirSync(dataOut, { recursive: true });
let files = 0;
for (const f of readdirSync(dataSrc)) {
  const p = join(dataSrc, f);
  if (!statSync(p).isFile()) continue;
  copyFileSync(p, join(dataOut, f));
  files++;
}

// Build date of the data, for the top bar.
let built = null;
try {
  const head = readFileSync(join(dataSrc, "segments.json"), "utf8").slice(0, 400);
  built = head.match(/"built":"([^"]+)"/)?.[1] ?? null;
} catch {
  /* no segments.json */
}
writeFileSync(join(libOut, "build-info.ts"), `${HEADER}export const DATA_BUILT: string | null = ${JSON.stringify(built)};\n`);
console.log(`sync-shared: ${done.size} lib files, ${files} data files, data built ${built ?? "unknown"}`);
