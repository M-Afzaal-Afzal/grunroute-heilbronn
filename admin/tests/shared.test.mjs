// The Planner reads copies of the root scoring code and data. These checks
// make sure the copies exist, carry the "generated" header, and match the root.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";

const HEADER = "// generated by admin/scripts/sync-shared.mjs";

test("shared lib copies carry the generated header and match the root files", () => {
  const files = readdirSync(new URL("../lib/shared/", import.meta.url)).filter((f) => f !== "build-info.ts");
  assert.ok(files.includes("priority.ts"));
  for (const f of files) {
    const copy = readFileSync(new URL(`../lib/shared/${f}`, import.meta.url), "utf8");
    assert.ok(copy.startsWith(HEADER), `${f} header`);
    const root = readFileSync(new URL(`../../lib/${f}`, import.meta.url), "utf8");
    assert.equal(copy.slice(copy.indexOf("\n") + 1), root, `${f} matches root`);
  }
});

test("data copies match the root data", () => {
  for (const f of readdirSync(new URL("../../public/data/", import.meta.url))) {
    const a = readFileSync(new URL(`../public/data/${f}`, import.meta.url));
    const b = readFileSync(new URL(`../../public/data/${f}`, import.meta.url));
    assert.ok(a.equals(b), f);
  }
});
